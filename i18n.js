// ===== Language Switching Logic =====
function initLanguageSwitcher() {
    const langToggle = document.getElementById('langToggle');
    const langDropdown = document.getElementById('langDropdown');
    const langCurrent = langToggle ? langToggle.querySelector('.lang-current') : null;
    const langOptions = document.querySelectorAll('.lang-option');

    if (!langToggle || !langDropdown) return;

    // Load saved language
    const savedLang = localStorage.getItem('lang') || 'en';
    applyLanguage(savedLang);
    updateActiveLang(savedLang);

    // Toggle dropdown
    langToggle.addEventListener('click', function(e) {
        e.stopPropagation();
        langDropdown.classList.toggle('open');
    });

    // Close dropdown on outside click
    document.addEventListener('click', function() {
        langDropdown.classList.remove('open');
    });

    // Language option click
    langOptions.forEach(function(btn) {
        btn.addEventListener('click', function(e) {
            e.stopPropagation();
            const lang = this.getAttribute('data-lang');
            applyLanguage(lang);
            updateActiveLang(lang);
            localStorage.setItem('lang', lang);
            langDropdown.classList.remove('open');
        });
    });

    function updateActiveLang(lang) {
        langOptions.forEach(function(btn) {
            btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
        });
        var labels = { en: 'EN', kn: 'ಕ', hi: 'हि' };
        if (langCurrent) langCurrent.textContent = labels[lang] || 'EN';
    }
}

function applyLanguage(lang) {
    var t = translations[lang];
    if (!t) return;

    // Update text content for elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
        var key = el.getAttribute('data-i18n');
        if (t[key]) {
            el.innerHTML = t[key];
        }
    });

    // Update placeholders for inputs with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
        var key = el.getAttribute('data-i18n-placeholder');
        if (t[key]) {
            el.setAttribute('placeholder', t[key]);
        }
    });

    // Update html lang attribute
    var langMap = { en: 'en', kn: 'kn', hi: 'hi' };
    document.documentElement.setAttribute('lang', langMap[lang] || 'en');
}

// Initialize on DOM ready
document.addEventListener('DOMContentLoaded', initLanguageSwitcher);
